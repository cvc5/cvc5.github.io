#!/usr/bin/env python3
"""Generate the cvc5.github.io award pages for one SMT-COMP year.

Input is a checkout of https://github.com/SMT-COMP/smt-comp.github.io at the
year's tag (e.g. `smtcomp24`), prepared with

  smtcomp create-cache data
  smtcomp export-results-pages data <Track>   # for every track in TOTAL_TRACKS

Output, in this repository (or SITE_REPO):

  _awards/smt-comp-<year>.md   details page (layout: awards)
  _data/awards.yml             the year's summary entry, shown by awards.md

usage: gen_awards.py SMTCOMP_REPO [SITE_REPO] [--solver cvc5] [--dry-run]

Supports the years whose website is generated by that repository (2024+).
Rules not stated by the competition itself:
  - silver/bronze in competition-wide rankings are inferred (see `ranking`);
  - only TRACKS are listed; "out of" totals also count PARALLEL; Cloud is never used.

AI usage: Script was fully generated by Claude Code.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from collections import defaultdict
from dataclasses import dataclass
from functools import cached_property
from pathlib import Path

# --------------------------------------------------------------------------
# Competition structure
# --------------------------------------------------------------------------

# Award categories: winner-field suffix -> (row-list key in results, name on our pages).
CATEGORIES = {
    "seq": ("sequential", "sequential"),
    "par": ("parallel", "parallel"),
    "sat": ("sat", "sat"),
    "unsat": ("unsat", "unsat"),
    "24s": ("twentyfour", "24s"),
}


@dataclass(frozen=True)
class Track:
    slug: str  # in URLs and file names, e.g. "single-query"
    name: str  # display name
    submission: str  # name in submissions/*.json, e.g. "SingleQuery"
    categories: tuple[str, ...] = tuple(CATEGORIES)


SINGLE_QUERY = Track("single-query", "Single Query Track", "SingleQuery")
# No sequential award in Incremental (cf. web/themes/smtcomp/layouts/_default/result.html).
INCREMENTAL = Track("incremental", "Incremental Track", "Incremental", ("par", "sat", "unsat", "24s"))
UNSAT_CORE = Track("unsat-core", "Unsat Core Track", "UnsatCore")
MODEL_VALIDATION = Track("model-validation", "Model Validation Track", "ModelValidation")
PARALLEL = Track("parallel", "Parallel Track", "Parallel")

# Tracks listed on our pages; the Cloud Track is never used.
TRACKS = (SINGLE_QUERY, INCREMENTAL, UNSAT_CORE, MODEL_VALIDATION)
# Tracks counted in the "out of" totals of the summary.
TOTAL_TRACKS = TRACKS + (PARALLEL,)
TRACK_BY_SLUG = {t.slug: t for t in TOTAL_TRACKS}

# Competition-wide recognitions (slug, name), in page order.
RECOGNITIONS = (
    ("best-overall", "Best Overall"),
    ("biggest-lead", "Biggest Lead"),
    ("largest-contribution", "Largest Contribution"),
)
MEDALS = {1: "gold", 2: "silver", 3: "bronze"}

# --------------------------------------------------------------------------
# Loading (smt-comp.github.io)
# --------------------------------------------------------------------------


class Results:
    """Read access to one year of generated results pages and submissions."""

    def __init__(self, repo: Path):
        self.pages = repo / "web" / "content" / "results"
        self.submissions = [json.loads(p.read_text()) for p in sorted((repo / "submissions").glob("*.json"))]
        self.non_competing = {s["name"] for s in self.submissions if not s.get("competitive", True)}

    def _page(self, name: str) -> dict | None:
        path = self.pages / f"{name}.md"  # these .md files contain JSON
        return json.loads(path.read_text()) if path.exists() else None

    @cached_property
    def divisions(self) -> dict[Track, list[dict]]:
        """All division pages per track, as embedded in the track summary pages."""
        found = {}
        for track in TOTAL_TRACKS:
            page = self._page(f"results-{track.slug}")
            if page is None:
                sys.exit(f"no results for {track.name}: run `smtcomp export-results-pages data {track.submission}`")
            found[track] = sorted(page["divisions"], key=lambda d: d["division"].lower())
        return found

    @cached_property
    def year(self) -> int:
        """The year of the exported results (from the track summaries)."""
        years = {d["year"] for divisions in self.divisions.values() for d in divisions}
        assert len(years) == 1, f"results from several years: {sorted(years)}"
        return years.pop()

    def recognition(self, slug: str, track: Track) -> dict | None:
        """A competition-wide page, ignoring stale pages left by an export of another year."""
        page = self._page(f"{slug}-{track.slug}")
        return page if page and page["year"] == self.year else None

    def submission(self, solver: str) -> dict:
        return next(s for s in self.submissions if s["name"] == solver)


# --------------------------------------------------------------------------
# Analysis
# --------------------------------------------------------------------------


@dataclass
class Award:
    """One medal line: a division (or track) and the categories it covers."""

    where: str  # division name, or track slug for competition-wide awards
    place: int
    categories: list[str]
    complete: bool  # covers every category that has a winner, shown as "(all)"


@dataclass
class Year:
    """Everything shown for one solver in one year."""

    year: int
    entered: dict[str, list[str]]  # track slug -> divisions
    medals: dict[str, list[Award]]  # track slug -> division awards
    overall: list[tuple[str, str, list[Award]]]  # (slug, name, awards per track)
    division_total: int  # categories with a winner, over TOTAL_TRACKS
    overall_total: int

    def division_gold(self) -> int:
        return sum(len(a.categories) for awards in self.medals.values() for a in awards)

    def overall_medals(self, place: int) -> int:
        return sum(len(a.categories) for _, _, awards in self.overall for a in awards if a.place == place)


def winners(page: dict, track: Track) -> dict[str, str]:
    """Official winner per category; categories without a winner are left out."""
    found = {cat: page.get(f"winner_{cat}", "-") for cat in track.categories}
    return {cat: w for cat, w in found.items() if w not in ("-", "—", "")}


def solvers_in(page: dict) -> set[str]:
    return {row["name"] for key, _ in CATEGORIES.values() for row in page.get(key) or []}


def group(where: str, places: dict[str, int], categories: list[str]) -> list[Award]:
    """Turn {category: place} into one Award per place, best place first."""
    awards = []
    for place in sorted(set(places.values())):
        cats = [c for c in categories if places.get(c) == place]
        awards.append(Award(where, place, cats, cats == categories))
    return awards


def ranking(page: dict, slug: str, cat: str, non_competing: set[str]) -> list[str]:
    """Solvers that can place in a competition-wide ranking, best first.

    Silver/bronze are not official (the rules only define a winner): each
    solver is placed once, at its best row.
    """
    rows = page.get(CATEGORIES[cat][0]) or []
    if slug == "best-overall":
        # Sum of contributions. Only Best Overall rows carry `eligibleForWinning`,
        # matching the site, which applies the 2026 derived-solver rule only here.
        score: dict[str, float] = defaultdict(float)
        for row in rows:
            if row.get("eligibleForWinning", True):
                score[row["name"]] += row["contribution"]
        order = sorted(score, key=score.get, reverse=True)
    else:
        # Rows are ranked already; experimental divisions do not count.
        order = list(dict.fromkeys(r["name"] for r in rows if r.get("experimental") != "true"))
    return [s for s in order if s not in non_competing]


def division_awards(results: Results, solver: str) -> tuple[dict[str, list[str]], dict[str, list[Award]], int]:
    """Divisions entered and division medals per track, and the number of division awards."""
    entered: dict[str, list[str]] = {}
    medals: dict[str, list[Award]] = {}
    total = 0
    for track, divisions in results.divisions.items():
        for d in divisions:
            official = winners(d, track)
            total += len(official)
            if track not in TRACKS or solver not in solvers_in(d):
                continue
            entered.setdefault(track.slug, []).append(d["division"])
            won = {cat: 1 for cat, w in official.items() if w == solver}
            medals.setdefault(track.slug, []).extend(group(d["division"], won, list(official)))
    return entered, medals, total


def competition_wide_awards(results: Results, solver: str) -> tuple[list[tuple[str, str, list[Award]]], int]:
    """Places per recognition and track, and the number of competition-wide awards."""
    overall, total = [], 0
    for slug, name in RECOGNITIONS:
        pages = {t: results.recognition(slug, t) for t in TOTAL_TRACKS}
        if not any(pages.values()):
            continue  # recognition did not exist that year
        awards = []
        for track, page in pages.items():
            if page is None:
                sys.exit(f"no {slug} page for {track.name}")
            official = winners(page, track)
            total += len(official)
            places = {}
            for cat, winner in official.items():
                order = ranking(page, slug, cat, results.non_competing)
                # Guard against format or rule changes: our first place must be the official one.
                assert order[:1] == [winner], f"{slug}/{track.slug}/{cat}: computed {order[:1]}, official {winner}"
                if solver in order[:3]:
                    places[cat] = order.index(solver) + 1
            if track in TRACKS:
                awards += group(track.slug, places, list(official))
        overall.append((slug, name, awards))
    return overall, total


def analyze(results: Results, solver: str) -> Year:
    entered, medals, division_total = division_awards(results, solver)
    overall, overall_total = competition_wide_awards(results, solver)
    return Year(results.year, entered, medals, overall, division_total, overall_total)


# --------------------------------------------------------------------------
# Rendering
# --------------------------------------------------------------------------


def english_list(items: list[str]) -> str:
    return items[0] if len(items) == 1 else ", ".join(items[:-1]) + ", and " + items[-1]


def binaries(submission: dict, tracks: list[Track]) -> list[tuple[str, str]]:
    """(label, archive URL) per distinct archive of the submission."""
    by_url: dict[str, list[Track]] = defaultdict(list)
    for part in submission["participations"]:
        url = part.get("archive", submission["archive"])["url"]
        by_url[url] += [t for t in tracks if t.submission in part["tracks"]]
    by_url = {url: ts for url, ts in by_url.items() if ts}
    if len(by_url) == 1:
        return [("All Tracks", next(iter(by_url)))]
    label = lambda ts: english_list([t.name.removesuffix(" Track") for t in ts]) + (" Tracks" if len(ts) > 1 else " Track")
    return [(label(ts), url) for url, ts in by_url.items()]


def wrap(prefix: str, items: list[str], width: int = 80) -> list[str]:
    """`prefix` followed by comma-separated items, wrapped with a hanging indent."""
    lines, line = [], prefix
    for i, item in enumerate(items):
        piece = item + ("," if i < len(items) - 1 else "")
        if len(line) + len(piece) > width and line != prefix:
            lines.append(line.rstrip())
            line = " " * len(prefix)
        line += piece + " "
    return lines + [line.rstrip()]


def award_lines(a: Award, key: str) -> list[str]:
    lines = [f"  - {key}: {a.where}"]
    if key == "track":
        lines.append(f"    name: {TRACK_BY_SLUG[a.where].name}")
    if not a.complete:
        lines.append(f"    awards: {', '.join(CATEGORIES[c][1] for c in a.categories)}")
    return lines + [f"    place: {a.place}"]


def render_page(y: Year, solver: str, submission: dict) -> str:
    """The _awards/smt-comp-<year>.md details page."""
    tracks = [t for t in TRACKS if t.slug in y.entered]
    out = ["---", "layout: awards", "",
           f"event: SMT-COMP {y.year}",
           f"event_url: https://smt-comp.github.io/{y.year}",
           "division_url_sep: _",  # result URLs use '_' since 2024
           "", "version:", "binaries:"]
    for label, url in binaries(submission, tracks):
        out += [f"- name: {label}", f"  binary: {url}"]
    out += ["",
            f"sysdesc-title: {solver} at the SMT Competition {y.year}",
            f"sysdesc-url: {submission['system_description']}",
            "", "entered:"]
    for t in tracks:
        out += ["", f"- track: {t.slug}", f"  name: {t.name}", *wrap("  divisions: ", y.entered[t.slug])]
    out += ["", "tracks:"]
    for t in tracks:
        if y.medals.get(t.slug):
            out += ["", f"- track: {t.slug}", f"  name: {t.name}", "  medals:"]
            out += [line for a in y.medals[t.slug] for line in award_lines(a, "division")]
    out += ["", "overall:"]
    for slug, name, awards in y.overall:
        out += ["", f"- award: {slug}", f"  name: {name}", "  tracks:"]
        out += [line for a in awards for line in award_lines(a, "track")]
    return "\n".join(out + ["", "---", ""])


def render_summary(y: Year) -> str:
    """The year's `events` item in _data/awards.yml."""
    out = [f"  - event: SMT-COMP {y.year}",
           f"    event_url: http://smt-comp.github.io/{y.year}",
           f"    year: {y.year}",
           f"    entered: {sum(map(len, y.entered.values()))}",
           "    divisions:",
           f"      total: {y.division_total}",
           f"      gold: {y.division_gold()}",
           "    competition-wide:",
           f"      total: {y.overall_total}"]
    out += [f"      {medal}: {n}" for place, medal in MEDALS.items() if (n := y.overall_medals(place))]
    return "\n".join(out + [f"    details: /awards/smt-comp-{y.year}.html", ""])


# --------------------------------------------------------------------------
# Writing (cvc5.github.io)
# --------------------------------------------------------------------------

EVENT = re.compile(r"^  - event: SMT-COMP (\d+)\n(?:(?!  - event:).*\n?)*?(?=^\n|^  - event:|\Z)", re.M)


def update_summary(text: str, year: int, entry: str) -> str:
    """Replace the year's entry in awards.yml, or insert it keeping years descending."""
    events = list(EVENT.finditer(text))
    if not events:
        sys.exit("no SMT-COMP events found in awards.yml")
    for m in events:
        if int(m.group(1)) == year:
            return text[: m.start()] + entry + text[m.end():]
    older = next((m for m in events if int(m.group(1)) < year), None)
    if older:
        return text[: older.start()] + entry + "\n" + text[older.start():]
    end = events[-1].end()  # older than every entry: append after the last one
    return text[:end] + "\n" + entry + text[end:]


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("smtcomp_repo", type=Path, help="smt-comp.github.io checkout with generated results")
    parser.add_argument("site_repo", type=Path, nargs="?", default=Path(__file__).parent.parent.resolve(),
                        help="cvc5.github.io checkout (default: this repository)")
    parser.add_argument("--solver", default="cvc5")
    parser.add_argument("--dry-run", action="store_true", help="print instead of writing")
    args = parser.parse_args()

    results = Results(args.smtcomp_repo)
    y = analyze(results, args.solver)
    page = render_page(y, args.solver, results.submission(args.solver))
    summary_path = args.site_repo / "_data" / "awards.yml"
    summary = update_summary(summary_path.read_text(), y.year, render_summary(y))
    page_path = args.site_repo / "_awards" / f"smt-comp-{y.year}.md"

    print(f"{args.solver} at SMT-COMP {y.year}: {sum(map(len, y.entered.values()))} divisions entered, "
          f"{y.division_gold()}/{y.division_total} division gold, "
          f"competition-wide {'/'.join(str(y.overall_medals(p)) for p in MEDALS)} of {y.overall_total}",
          file=sys.stderr)
    if args.dry_run:
        print(page)
        print(render_summary(y))
        return
    page_path.write_text(page)
    summary_path.write_text(summary)
    print(f"wrote {page_path} and {summary_path}", file=sys.stderr)


if __name__ == "__main__":
    main()
